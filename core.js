// ============ Data Store ============
const store = {
    transactions: JSON.parse(localStorage.getItem('ting_transactions') || '[]'),
    settings: JSON.parse(localStorage.getItem('ting_settings') || '{}'),
    currentMonth: new Date(),
    
    save() {
        localStorage.setItem('ting_transactions', JSON.stringify(this.transactions));
        localStorage.setItem('ting_settings', JSON.stringify(this.settings));
    }
};

// ============ Utility Functions ============
const utils = {
    formatCurrency(amount) {
        return new Intl.NumberFormat('th-TH', {
            style: 'currency',
            currency: 'THB',
            minimumFractionDigits: 0,
            maximumFractionDigits: 2
        }).format(amount);
    },

    formatDate(dateStr) {
        const date = new Date(dateStr);
        return date.toLocaleDateString('th-TH', {
            day: 'numeric',
            month: 'short',
            year: 'numeric'
        });
    },

    formatMonthYear(date) {
        return date.toLocaleDateString('th-TH', {
            month: 'long',
            year: 'numeric'
        });
    },

    generateId() {
        return Date.now().toString(36) + Math.random().toString(36).substr(2);
    },

    getMonthTransactions(month, year) {
        return store.transactions.filter(t => {
            const date = new Date(t.date);
            return date.getMonth() === month && date.getFullYear() === year;
        });
    }
};

